// Bundles the shared modules + server core + the Apps Script wrapper into one
// paste-able file: apps-script/Code.gs. The Apps Script editor has no ES
// modules, so this strips import/export and concatenates in dependency order.
// Run: npm run build:script   (CI-free; commit the result).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BERKAS = [
  'src/lib/tarifHistoris.js', 'src/lib/tagihan.js', 'src/lib/rumah.js',
  'src/lib/ringkasan.js', 'src/server/core.js', 'src/server/gas.js',
];

// Syntax the Apps Script runtime may not have (it runs a V8 of its own vintage).
const TERLARANG = [
  [/\?\.(?![0-9])/, 'optional chaining (?.)'], [/\?\?/, 'nullish coalescing (??)'],
  [/\.at\(/, '.at()'], [/replaceAll\(/, 'replaceAll()'], [/structuredClone/, 'structuredClone'],
  [/\.toSorted\(/, 'toSorted()'],
];

export function bangun() {
  const bagian = BERKAS.map((f) => {
    let src = readFileSync(join(root, f), 'utf8');
    // single- and multi-line `import … from '…';`
    src = src.replace(/^import\s[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '');
    src = src.replace(/^export\s+(?=(const|let|function|async function|class)\b)/gm, '');
    if (/^export\b/m.test(src)) throw new Error(`${f}: unsupported export form`);
    if (/^import\b/m.test(src)) throw new Error(`${f}: import left over`);
    const kode = src.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
    for (const [re, nama] of TERLARANG) {
      if (re.test(kode)) throw new Error(`${f}: ${nama} is not safe for Apps Script`);
    }
    return `// ───── ${f} ─────\n${src.trim()}\n`;
  });
  return `// GENERATED by scripts/build-apps-script.mjs — do not edit here.
// Edit the files under src/ and run \`npm run build:script\`, then paste this
// whole file into the Apps Script editor (docs/setup.md, Tahap 6).

${bagian.join('\n')}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(join(root, 'apps-script'), { recursive: true });
  writeFileSync(join(root, 'apps-script/Code.gs'), bangun());
  console.log('apps-script/Code.gs written');
}
